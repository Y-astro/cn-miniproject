"""Message protocol implementation for UDP health monitoring."""

# Import standard JSON library for serializing/deserializing structured network payloads
import json
# Import type hinting primitives for static analysis and IDE autocompletion
from typing import Any, Dict, List, Optional

# Standard MTU is 1500 bytes; 1400 bytes leaves plenty of room for IP (20B) and UDP (8B) headers without fragmentation
MAX_DATAGRAM_SIZE = 1400
# Protocol version 1: allows future protocol upgrades while maintaining backward compatibility checks
SUPPORTED_VERSION = 1
# Allowable message types exchanged between agents and the central monitoring server
VALID_TYPES = {"HEALTH", "HEARTBEAT", "ALERT"}
# Traffic priority classifications used by the SDN controller for QoS queue mapping
VALID_PRIORITIES = {"NORMAL", "CRITICAL"}


# Custom exception class for all protocol encoding, decoding, and validation failures
class ProtocolError(Exception):
    """Raised when encoding, decoding, or validating a message fails."""
    # Inherit standard Exception behavior without additional modification
    pass


# Function to strictly validate all fields and value ranges of incoming/outgoing messages
def validate(msg: Dict[str, Any]) -> None:
    """Validates message structure, types, and metric ranges.

    Args:
        msg: Parsed message dictionary.

    Raises:
        ProtocolError: If any validation rule fails.
    """
    # Verify that the parsed payload is indeed a Python dictionary
    if not isinstance(msg, dict):
        # Raise error if payload is a list, string, integer, or other invalid type
        raise ProtocolError(f"Message must be a dictionary, got {type(msg).__name__}")

    # Extract the protocol version field from the message
    version = msg.get("version")
    # Verify the protocol version matches our supported version
    if version != SUPPORTED_VERSION:
        # Reject incompatible protocol versions immediately
        raise ProtocolError(f"Unsupported protocol version: {version}. Expected: {SUPPORTED_VERSION}")

    # Extract the message type field (HEALTH, HEARTBEAT, or ALERT)
    msg_type = msg.get("type")
    # Verify that the message type belongs to the permitted set
    if msg_type not in VALID_TYPES:
        # Reject any unknown or spoofed message types
        raise ProtocolError(f"Invalid message type '{msg_type}'. Expected one of {sorted(VALID_TYPES)}")

    # Extract the unique node identifier (e.g., 'h1_prod', 'h2_db')
    node_id = msg.get("node_id")
    # Verify that node_id is a non-empty string with non-whitespace content
    if not isinstance(node_id, str) or not node_id.strip():
        # Reject empty, null, or non-string node identifiers
        raise ProtocolError(f"Invalid node_id: '{node_id}'. Must be a non-empty string.")

    # Extract the sequence number for packet loss and out-of-order tracking
    seq = msg.get("seq")
    # Verify that seq is an integer (and not a boolean subclass) >= 0
    if not isinstance(seq, int) or isinstance(seq, bool) or seq < 0:
        # Reject invalid sequence numbers
        raise ProtocolError(f"Invalid sequence number: {seq}. Must be an integer >= 0.")

    # Extract the transmission timestamp generated by the sender agent
    sent_ts = msg.get("sent_ts")
    # Verify that sent_ts is a positive float or integer (epoch timestamp)
    if not isinstance(sent_ts, (int, float)) or isinstance(sent_ts, bool) or sent_ts <= 0:
        # Reject invalid or zero timestamps
        raise ProtocolError(f"Invalid sent_ts timestamp: {sent_ts}. Must be a positive float/int.")

    # Extract the priority level (NORMAL or CRITICAL)
    priority = msg.get("priority")
    # Verify priority is one of the supported QoS categories
    if priority not in VALID_PRIORITIES:
        # Reject invalid traffic priorities
        raise ProtocolError(f"Invalid priority '{priority}'. Expected one of {sorted(VALID_PRIORITIES)}")

    # Extract the optional or required metrics dictionary
    metrics = msg.get("metrics")
    # HEALTH and ALERT messages require telemetry metrics
    if msg_type in {"HEALTH", "ALERT"}:
        # Check that metrics dictionary is provided
        if not isinstance(metrics, dict):
            # Reject HEALTH/ALERT messages lacking metric payload
            raise ProtocolError(f"Message type '{msg_type}' requires a 'metrics' dict.")

    # If metrics are present, validate individual metric fields
    if metrics is not None:
        # Ensure metrics container is a valid dictionary
        if not isinstance(metrics, dict):
            # Reject non-dictionary metrics structures
            raise ProtocolError(f"'metrics' must be a dict, got {type(metrics).__name__}")

        # Extract CPU utilization percentage
        cpu = metrics.get("cpu_percent")
        # Validate CPU utilization if present
        if cpu is not None:
            # Check numeric type and bounds between 0.0% and 100.0%
            if not isinstance(cpu, (int, float)) or isinstance(cpu, bool) or not (0.0 <= cpu <= 100.0):
                # Reject impossible CPU percentage values
                raise ProtocolError(f"Invalid cpu_percent: {cpu}. Must be between 0.0 and 100.0.")

        # Extract memory utilization percentage
        mem = metrics.get("mem_percent")
        # Validate memory utilization if present
        if mem is not None:
            # Check numeric type and bounds between 0.0% and 100.0%
            if not isinstance(mem, (int, float)) or isinstance(mem, bool) or not (0.0 <= mem <= 100.0):
                # Reject impossible RAM percentage values
                raise ProtocolError(f"Invalid mem_percent: {mem}. Must be between 0.0 and 100.0.")

        # Extract active system process count
        proc_count = metrics.get("process_count")
        # Validate process count if present
        if proc_count is not None:
            # Must be a non-negative integer
            if not isinstance(proc_count, int) or isinstance(proc_count, bool) or proc_count < 0:
                # Reject negative or invalid process counts
                raise ProtocolError(f"Invalid process_count: {proc_count}. Must be an integer >= 0.")

        # Extract list of top resource-consuming processes
        top_procs = metrics.get("top_processes")
        # Validate that top processes is formatted as a list
        if top_procs is not None and not isinstance(top_procs, list):
            # Reject malformed process listings
            raise ProtocolError(f"top_processes must be a list, got {type(top_procs).__name__}")

        # Extract network interface I/O statistics
        net = metrics.get("net")
        # Validate network stats dictionary if present
        if net is not None:
            # Ensure network stats is a dictionary
            if not isinstance(net, dict):
                # Reject non-dictionary network structures
                raise ProtocolError(f"'net' metrics must be a dict, got {type(net).__name__}")
            # Iterate through standard network accounting counters
            for net_key in ["bytes_sent", "bytes_recv", "packets_sent", "packets_recv", "errors"]:
                # Check each network key if present
                if net_key in net:
                    # Retrieve the counter value
                    val = net[net_key]
                    # Verify counter is a non-negative integer
                    if not isinstance(val, int) or isinstance(val, bool) or val < 0:
                        # Reject invalid counter values
                        raise ProtocolError(f"Invalid net stat '{net_key}': {val}. Must be an int >= 0.")


# Function to serialize a Python dictionary into compact UTF-8 JSON network bytes
def encode(msg: Dict[str, Any], max_bytes: int = MAX_DATAGRAM_SIZE) -> bytes:
    """Validates and encodes a message dictionary to UTF-8 JSON bytes.

    Args:
        msg: Message dictionary.
        max_bytes: Maximum allowed payload size.

    Returns:
        bytes: Encoded payload.

    Raises:
        ProtocolError: If message is invalid or exceeds max_bytes.
    """
    # Enforce strict schema and range validation before serialization
    validate(msg)
    # Attempt JSON serialization into compact bytes
    try:
        # Use separators (',', ':') to eliminate all unnecessary whitespace and save bandwidth
        raw = json.dumps(msg, separators=(",", ":")).encode("utf-8")
    # Catch any serialization errors (e.g., non-serializable objects)
    except Exception as exc:
        # Wrap underlying error in standard ProtocolError
        raise ProtocolError(f"Failed to JSON-encode message: {exc}") from exc

    # Enforce datagram size boundary to guarantee single-packet UDP transmission
    if len(raw) > max_bytes:
        # Raise error if datagram would exceed safe MTU limit
        raise ProtocolError(
            f"Encoded payload size ({len(raw)} bytes) exceeds maximum datagram size ({max_bytes} bytes)"
        )
    # Return encoded byte array ready for socket transmission
    return raw


# Function to deserialize and validate incoming UDP network bytes into a Python dict
def decode(data: bytes, max_bytes: int = MAX_DATAGRAM_SIZE) -> Dict[str, Any]:
    """Decodes raw UDP datagram bytes to a validated message dictionary.

    Args:
        data: Raw payload bytes received from UDP socket.
        max_bytes: Maximum acceptable payload size.

    Returns:
        Dict[str, Any]: Validated message dict.

    Raises:
        ProtocolError: On empty payload, JSON decode failure, or validation failure.
    """
    # Check if incoming datagram buffer is empty
    if not data:
        # Reject zero-length payloads immediately
        raise ProtocolError("Received empty or zero-length payload")

    # Guard against oversized buffer overflow attempts
    if len(data) > max_bytes:
        # Reject packets that exceed maximum acceptable datagram size
        raise ProtocolError(f"Received payload size ({len(data)} bytes) exceeds maximum limit ({max_bytes} bytes)")

    # Attempt decoding UTF-8 text and parsing JSON structure
    try:
        # Decode raw network bytes into UTF-8 string
        text = data.decode("utf-8")
        # Parse JSON string into Python dictionary
        msg = json.loads(text)
    # Catch invalid character encoding sequences
    except UnicodeDecodeError as exc:
        # Raise protocol error on UTF-8 decode failure
        raise ProtocolError(f"UTF-8 decoding error: {exc}") from exc
    # Catch syntax errors in the JSON payload
    except json.JSONDecodeError as exc:
        # Raise protocol error on invalid JSON
        raise ProtocolError(f"Invalid JSON payload: {exc}") from exc
    # Catch any other unexpected decoding issues
    except Exception as exc:
        # Raise protocol error on malformed content
        raise ProtocolError(f"Malformed payload: {exc}") from exc

    # Run complete schema and range validation on the parsed object
    validate(msg)
    # Return validated message dictionary to the caller
    return msg
